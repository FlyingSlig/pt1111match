#!/usr/bin/env python3
"""Emit src/zzzz_eh_stubs.cpp: one `mov eax, <FuncInfo>; jmp __CxxFrameHandler`
stub per SEH handler of the original binary, plus a const FuncInfo header per
unique FuncInfo address.

reccmp detects `__ehhandler` LABEL entities in an image by combining
  * a const-region struct whose first dword is the FuncInfo magic 0x19930520,
  * a code sequence `B8 <funcinfo VA> E9` (mov eax; jmp).
The original game TUs' stubs live in the tail of .text; our raw bodies do not
create them, so `push __ehhandler` could never resolve in our image.  With
these stubs the rewriter can emit `push OFFSET pt_eh_stub_<addr>` and reccmp
sees `__ehhandler` on both sides.

The FuncInfo copies currently carry magic + maxState=0 + a unique dword (so
the arrays are not identical).  The real unwind tables are Phase-4 byte work;
detection only needs the magic.
"""
import csv
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

rows = []
for line in open('ghidra/export/eh_handlers.tsv').read().splitlines()[1:]:
    if not line.strip():
        continue
    h, f = line.split('\t')
    rows.append((int(h, 16), int(f, 16)))
rows.sort()

# All stubs share one FuncInfo header.  reccmp only needs the magic at the
# address named by `mov eax` to synthesise the __ehhandler label, so a single
# 12-byte struct is enough and saves 6,132 B of .rdata versus one copy per
# original FuncInfo.  (The real per-function unwind tables are Phase-4 work.)
out = ['// auto-generated by tools/gen_eh_stubs.py',
       '// SEH funclet stubs + one shared FuncInfo header for the raw game TUs.',
       'extern "C" void __CxxFrameHandler();',
       '',
       'extern "C" const unsigned char pt_eh_fci_shared[12] = {',
       '    0x20, 0x05, 0x93, 0x19,   // FuncInfo magic (VC7.1)',
       '    0x00, 0x00, 0x00, 0x00,   // maxState = 0 (unwind tables: Phase 4)',
       '    0x00, 0x00, 0x00, 0x00,',
       '};',
       '']

out.append('// Handler address = the `mov eax` site (matches reccmp/FuncInfo parser).')
for h, f in rows:
    out.append('extern "C" __declspec(naked) void pt_eh_stub_%08x(void)' % h)
    out.append('{')
    out.append('    __asm {')
    out.append('        mov eax, OFFSET pt_eh_fci_shared')
    out.append('        jmp __CxxFrameHandler')
    out.append('    }')
    out.append('}')
    out.append('')

open('src/zzzz_eh_stubs.cpp', 'w').write('\n'.join(out))
print('wrote %d stubs + 1 shared FuncInfo' % len(rows))
