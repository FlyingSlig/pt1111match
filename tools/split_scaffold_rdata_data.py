#!/usr/bin/env python3
"""Split the Phase-4 scaffold into separate `.rdata` and `.data` objects.

`src/0999_globals_phase4.cpp` holds both kinds of global.  The `.rdata` blocks
need to be linked *before* the STL objects so the first game-data block can be
aligned to the original `0xbc3a0` after `tools/compact_rdata_prologue.py`.
Moving the whole file also moves its `.data` blocks, which changes the
linker's `.data` raw size (0xc000 -> 0xa000).  This script writes:

  * `src/0099a_globals_rdata.cpp` - every `extern const` block, with the
    `PTR_*` IAT-slot copies moved last.  It sorts before `0100_stl_*`.
  * `src/0999_globals_phase4.cpp` - every non-const `.data` block, in the
    original order, so its link position and `.data` raw size are unchanged.

Run after regenerating/filling the scaffold and before `make`.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

SRC = 'src/0999_globals_phase4.cpp'
RDATA = 'src/0099a_globals_rdata.cpp'
IAT_LO, IAT_HI = 0x4BC000, 0x4BC39C

lines = open(SRC).read().splitlines()
blocks = []
i = 0
while i < len(lines):
    m = re.match(r'// GLOBAL: PORT1111 0x([0-9a-fA-F]+)', lines[i])
    if not m:
        i += 1
        continue
    addr = int(m.group(1), 16)
    marker = lines[i]
    i += 1
    while i < len(lines) and (lines[i].startswith('//') or
                              not lines[i].strip()):
        i += 1
    decl = lines[i]
    i += 1
    blocks.append((addr, marker, decl))

rdata = [b for b in blocks if 'const' in b[2] and
         'unsigned char' in b[2]]
data = [b for b in blocks if b not in rdata]
print('blocks: %d .rdata, %d .data' % (len(rdata), len(data)))

iat = [b for b in rdata if b[0] >= IAT_LO and b[0] < IAT_HI and
       'PTR_' in b[2]]
rest = [b for b in rdata if b not in iat]
print('  %d PTR_ IAT copies moved last' % len(iat))

out = ['// Phase-4 `.rdata` scaffold: linked before the STL objects so the',
       '// first game-data block can be placed at the original 0xbc3a0.',
       '// Generated by tools/split_scaffold_rdata_data.py.', '']
for _addr, marker, decl in rest:
    out.append(marker)
    out.append(decl)
out.append('')
out.append('// IAT-slot copies (the real IAT is rebuilt at 0xbc000)')
for _addr, marker, decl in iat:
    out.append(marker)
    out.append(decl)
open(RDATA, 'w').write('\n'.join(out) + '\n')

out = ['// Phase-4 `.data` scaffold: kept at its original link position so the',
       '// linker .data raw size stays 0xc000.',
       '// Generated by tools/split_scaffold_rdata_data.py.', '']
for _addr, marker, decl in data:
    out.append(marker)
    out.append(decl)
open(SRC, 'w').write('\n'.join(out) + '\n')
print('wrote', RDATA, 'and', SRC)
