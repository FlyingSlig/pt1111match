#!/usr/bin/env python3
"""Reset every `// GAP:` naked filler body to the original bytes as `_emit`.

Gap fillers are not regenerated by tools/rewrite_layout_chunks.py, and
tools/symbolize_gap_imports.py assumes one `_emit` per byte.  After that tool
has introduced symbolic `call/jmp dword ptr [Name]` lines, its byte-offset
mapping no longer holds.  Run this first to get a clean all-`_emit` body, then
symbolize_gap_imports.py.

The byte length of the current body is recovered by counting `_emit` as one
byte and `call/jmp dword ptr [..]` as six.
"""
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
from ptconfig import ORIG_EXE
EXE = ORIG_EXE
d = open(EXE, 'rb').read()


def orig(va, n):
    return d[4096 + (va - 0x400000 - 0x1000):][:n]


def body_len(lines):
    n = 0
    for l in lines:
        s = l.strip()
        if s.startswith('_emit'):
            n += 1
        elif re.match(r'^(call|jmp) dword ptr \[', s):
            n += 6
        elif s in ('}',):
            break
        else:
            raise ValueError('unexpected line in gap body: %r' % s)
    return n


total = 0
for fn in sorted(glob.glob('src/*_layout.cpp')):
    lines = open(fn, errors='replace').read().splitlines()
    out = []
    i = 0
    changed = False
    while i < len(lines):
        m = re.match(r'// GAP: PORT1111 (0x[0-9a-f]+)', lines[i])
        if not m:
            out.append(lines[i])
            i += 1
            continue
        addr = int(m.group(1), 16)
        # copy through to the __asm { line
        while i < len(lines) and lines[i].strip() != '__asm {':
            out.append(lines[i])
            i += 1
        out.append(lines[i])  # __asm {
        i += 1
        body = []
        while i < len(lines) and lines[i].strip() != '}':
            body.append(lines[i])
            i += 1
        n = body_len(body)
        raw = orig(addr, n)
        if len(raw) != n:
            print('short read', fn, hex(addr), n, len(raw))
        out.extend('        _emit 0x%02x' % x for x in raw)
        out.append('    }')
        total += 1
        changed = True
        # skip the original closing brace line
        while i < len(lines) and lines[i].strip() != '}':
            i += 1
        i += 1
    if changed:
        open(fn, 'w').write('\n'.join(out) + '\n')
print('reset %d gap bodies' % total)
