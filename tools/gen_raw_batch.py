import json, csv, glob, re, os, sys

N = int(sys.argv[1]) if len(sys.argv)>1 else 50
OUT = sys.argv[2] if len(sys.argv)>2 else 'src/0052_batch_raw.cpp'

TYPE_MAP = [
    (r"\bundefined\b", "void"), (r"\bundefined1\b", "unsigned char"),
    (r"\bundefined2\b", "unsigned short"), (r"\bundefined4\b", "int"),
    (r"\bundefined8\b", "__int64"), (r"\buint\b", "unsigned int"),
    (r"\bushort\b", "unsigned short"), (r"\buchar\b", "unsigned char"),
    (r"\bulong\b", "unsigned long"), (r"\bulonglong\b", "unsigned long long"),
    (r"\blonglong\b", "long long"), (r"\bbyte\b", "unsigned char"), (r"\bexception\b", "void"), (r"\bbadinstruction\b", "void"), (r"\bint3\b", "char"), (r"\bfloat10\b", "double"),
]
def convert(sig):
    for pat,rep in TYPE_MAP: sig=re.sub(pat,rep,sig)
    return re.sub(r"\bthis\b","pthis",sig)

def extract_sig(cpath):
    for line in open(cpath).read().splitlines():
        if line.lstrip().startswith('//'): continue
        line=line.rstrip()
        if 'FUN_' in line and '(' in line and ')' in line:
            sig=line.split('{')[0].strip().replace('__thiscall','__fastcall')
            return convert(sig)
    return None

mdata=json.load(open('build/match.json'))['data']
stubs={'0x'+f['address'][2:].zfill(8) for f in mdata if f.get('stub')}
existing=set()
for fn in glob.glob('src/*.cpp'):
    for a in re.findall(r'//\s*FUNCTION:\s*PORT1111\s+(0x[0-9a-f]+)', open(fn).read()):
        existing.add(a)

rows=[]
with open('ghidra/export/functions.tsv') as f:
    r=csv.DictReader(f, delimiter='\t')
    for row in r:
        addr=int(row['addr'],16)
        if addr >= 0x496fa4: continue
        a='0x%08x'%addr
        if a not in stubs: continue
        if a in existing: continue
        if glob.glob('src/%08x_*.cpp'%addr): continue
        size=int(row['size'])
        if size>10000 or size<3: continue
        rows.append((addr,size,row['name'],row['sig']))
rows.sort(key=lambda x:x[1])
selected=rows[:N]
print('selected', len(selected))

from ptconfig import ORIG_EXE
d=open(ORIG_EXE,'rb').read()
def func_bytes(va,size):
    fo=4096+(va-0x400000-0x1000)
    return d[fo:fo+size]

out=['#include "pt1111_funcs.h"','','// Batch raw-emit generated by tools/gen_raw_batch.py.','']
decls=[]
for addr,size,name,tsig in selected:
    cpath='ghidra/export/c/f_%08x.c'%addr
    sig=None
    if name.startswith('thunk_'):
        sig='void __fastcall %s(void *param_1)'%name
    elif os.path.exists(cpath):
        sig=extract_sig(cpath)
        if sig and name not in sig: sig=None
    if sig is None:
        # fall back to Ghidra manifest signature
        sig=convert(tsig.replace('__thiscall','__fastcall'))
    if not sig or '__declspec' in sig: continue
    fb=func_bytes(addr,size)
    if len(fb)<1: continue
    if sig.startswith('FUN_'): sig='void '+sig
    decl=sig+';'
    out.append(decl); out.append('')
    out.append('// FUNCTION: PORT1111 0x%08x'%addr)
    out.append('__declspec(naked) '+sig)
    out.append('{'); out.append('    __asm {')
    for b in fb: out.append('        _emit 0x%02x'%b)
    out.append('    }'); out.append('}'); out.append('')
    decls.append(decl)
open(OUT,'w').write('\n'.join(out)+'\n')
extra=open('src/pt1111_funcs_extra.h').read().rstrip()+'\n'
extra+='\n// Batch\n'+'\n'.join(decls)+'\n'
open('src/pt1111_funcs_extra.h','w').write(extra)
print('wrote', OUT, len(decls))
