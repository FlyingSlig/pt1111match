#!/usr/bin/env python3
"""Generate relocated switch tables for the raw layout code.

The original stores jump-table case labels as **absolute addresses** in code
gaps (``jmp dword ptr [reg*4 + table]``).  Copying those bytes verbatim only
works while every function sits at its original address; with layout drift a
case target lands in a different function and the game jumps mid-instruction.

MSVC 7.1's inline assembler cannot emit ``dd OFFSET symbol``, so instead this
tool moves each table into C++ data:

  * ``src/0112_switch_tables.cpp`` defines
    ``void *const pt_swt_<table_va>[n] = {(void*)((char*)FUN_x + delta), ...};``
    - real link-time relocations, valid at every build.
  * ``src/pt_switch_map.txt`` maps the original table address to the array
    symbol; ``rewrite_layout_chunks.py`` rewrites
    ``[reg*4 + <original table>]`` to ``[reg*4 + pt_swt_<va>]``.

Entries whose target is not a listed function keep the original numeric value
(they are rare; see the warning output).  The gap still contains the original
table bytes, unused.

Run before ``make`` and before ``rewrite_layout_chunks.py`` (or re-run the
rewriter after generating the map).
"""
import bisect
import csv
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

from ptconfig import ORIG_EXE
EXE = ORIG_EXE
OUT_CPP = 'src/0112_switch_tables.cpp'
OUT_MAP = 'src/pt_switch_map.txt'

orig = open(EXE, 'rb').read()


def obytes(va, n):
    off = va - 0x400000
    return orig[off:off + n]


funcs = []
for row in csv.DictReader(open('ghidra/export/functions.tsv'), delimiter='\t'):
    funcs.append((int(row['addr'], 16), int(row['size'])))
funcs.sort()
fstarts = [f[0] for f in funcs]


def func_of(va):
    i = bisect.bisect_right(fstarts, va) - 1
    if i < 0:
        return None
    a, s = funcs[i]
    return a if a <= va < a + s else None


gaps = []
for r in csv.DictReader(open('ghidra/export/text_layout.tsv'), delimiter='\t'):
    if r['kind'] == 'gap':
        gaps.append((int(r['start'], 16), int(r['size'])))
gaps.sort()
gstarts = [g[0] for g in gaps]


def gap_of(va):
    i = bisect.bisect_right(gstarts, va) - 1
    if i < 0:
        return None
    a, s = gaps[i]
    return a if a <= va < a + s else None


SIB = {0x85, 0x8D, 0x95, 0x9D, 0xA5, 0xAD, 0xB5, 0xBD}
tables = {}
for va in range(0x401000, 0x496FA4 - 7):
    b = obytes(va, 3)
    if len(b) < 3:
        continue
    if b[0] == 0xFF and b[1] in (0x24, 0x14) and b[2] in SIB:
        table_va = struct.unpack_from('<I', obytes(va + 3, 4), 0)[0]
        if gap_of(table_va) is None:
            continue
        entries = []
        for i in range(256):
            e = struct.unpack_from('<I', obytes(table_va + 4 * i, 4), 0)[0]
            if e == 0xCCCCCCCC or not (0x401000 <= e < 0x496FA4):
                break
            entries.append(e)
        if len(entries) >= 2:
            tables[table_va] = entries

print('switch tables in code gaps:', len(tables))

lines = [
    '// pt1111match - relocated switch tables (generated by '
    'tools/gen_switch_tables.py).',
    '// The original keeps these as absolute case-label addresses in code gaps;',
    '// our layout drift requires real relocations, so the raw code reads the',
    '// matching array from here instead.',
    '#include "pt1111_funcs.h"',
    '#include "pt1111_funcs_extra.h"',
    '',
]
map_lines = [
    '# original table VA -> our array symbol (used by rewrite_layout_chunks.py)',
]
unknown = 0
emitted = 0
for table_va in sorted(tables):
    entries = tables[table_va]
    sym = 'pt_swt_%08x' % table_va
    map_lines.append('%08x %s' % (table_va, sym))
    lines.append('void *%s[%d] = {' % (sym, len(entries)))
    for e in entries:
        f = func_of(e)
        if f is None:
            unknown += 1
            lines.append('    (void *)0x%08X,  // unmapped original address' % e)
            continue
        delta = e - f
        expr = '(char *)FUN_%08x' % f
        if delta:
            expr += ' + %d' % delta
        lines.append('    (void *)(%s),' % expr)
    lines.append('};')
    lines.append('')
    emitted += len(entries)

open(OUT_CPP, 'w').write('\n'.join(lines) + '\n')
open(OUT_MAP, 'w').write('\n'.join(map_lines) + '\n')
print('wrote %s: %d tables, %d entries (%d unmapped kept as raw addresses)'
      % (OUT_CPP, len(tables), emitted, unknown))
