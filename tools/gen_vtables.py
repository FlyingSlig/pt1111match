#!/usr/bin/env python3
"""Generate symbolic code-pointer arrays for the data scaffold.

Ghidra lists the original's vtables/callback tables as consecutive 4-byte
``PTR_FUN_<addr>`` symbols.  Our scaffold mirrored them as zero 4-byte arrays
(the fill script skips blobs containing image-range pointers), so a raw
constructor that stores a vtable base gets a table of zeros and the first
virtual call jumps to NULL.

This tool reads the original bytes at each ``PTR_FUN_*`` address, follows the
run of consecutive code pointers, and emits a real C++ array::

    void *pt_vt_004bc854[4] = {
        (void *)((char *)FUN_00468140 + 0), ...
    };

``src/pt_vtable_map.txt`` maps the original base address to the array symbol;
``rewrite_layout_chunks.py`` then references the array instead of the zero
scaffold.  The symbols are ordinary link-time relocations, so they stay valid
across layout changes.
"""
import bisect
import csv
import os
import re
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

from ptconfig import ORIG_EXE
EXE = ORIG_EXE
SCAFFOLD = 'src/0999_globals_phase4.cpp'
OUT_CPP = 'src/0113_vtables.cpp'
OUT_MAP = 'src/pt_vtable_map.txt'

orig = open(EXE, 'rb').read()


def obytes(va, n):
    off = va - 0x400000
    return orig[off:off + n]


funcs = []
for row in csv.DictReader(open('ghidra/export/functions.tsv'), delimiter='\t'):
    funcs.append((int(row['addr'], 16), int(row['size'])))
funcs.sort()
fstarts = [f[0] for f in funcs]


def func_of(va):
    i = bisect.bisect_right(fstarts, va) - 1
    if i < 0:
        return None
    a, s = funcs[i]
    return a if a <= va < a + s else None


# original function -> decorated symbol of our implementation (from the last
# build).  Members/pattern-matched functions have no FUN_ name; the vtable
# stores their address through an extern "C" alias renamed by the linker
# patcher (src/pt_vtable_alias.txt).
import json
recomp = {}
try:
    for f in json.load(open('build/match.json'))['data']:
        if f.get('recomp'):
            recomp[int(f['address'], 16)] = int(f['recomp'], 16)
except Exception:
    pass
sym_at = {}
for line in open('build/Port1111.map', errors='replace'):
    m = re.match(r'\s*0001:[0-9A-Fa-f]{8}\s+(\S+)\s+([0-9a-fA-F]{8})\s', line)
    if m:
        sym_at[int(m.group(2), 16)] = m.group(1)


def decorated_for(orig_addr):
    r = recomp.get(orig_addr)
    return sym_at.get(r) if r is not None else None


declared = set()
for h in ('src/pt1111_funcs.h', 'src/pt1111_funcs_extra.h'):
    if os.path.exists(h):
        for m in re.finditer(r'\bFUN_([0-9a-f]{8})\b', open(h).read()):
            declared.add(int(m.group(1), 16))

# scaffold PTR_FUN entries (base address + declared size)
bases = []
pat = re.compile(r'^(?:extern const )?unsigned char PTR_FUN_([0-9a-f]{8})\[(\d+)\]')
for line in open(SCAFFOLD):
    m = pat.match(line.strip())
    if m:
        bases.append((int(m.group(1), 16), int(m.group(2))))
bases.sort()
seen = set()
arrays = []
skipped = 0
for base, _size in bases:
    if base in seen:
        continue
    # follow the run of code pointers
    entries = []
    for i in range(256):
        v = struct.unpack_from('<I', obytes(base + 4 * i, 4), 0)[0]
        if v == 0 or func_of(v) is None:
            break
        entries.append(v)
    if not entries:
        skipped += 1
        continue
    for k in range(len(entries)):
        seen.add(base + 4 * k)
    arrays.append((base, entries))

print('PTR_FUN bases: %d; arrays: %d (%d without code target), entries: %d'
      % (len(bases), len(arrays), skipped, sum(len(e) for _, e in arrays)))

lines = [
    '// pt1111match - symbolic code-pointer tables (generated by '
    'tools/gen_vtables.py).',
    '// The original stores absolute function addresses in these tables; our',
    '// layout drift requires relocations, so raw constructors reference these',
    '// arrays instead of the zero scaffold entries.',
    '#include "pt1111_funcs.h"',
    '#include "pt1111_funcs_extra.h"',
    '',
]
aliases = {}
map_lines = ['# original table base -> our array symbol']
for base, entries in arrays:
    sym = 'pt_vt_%08x' % base
    map_lines.append('%08x %s' % (base, sym))
    lines.append('void *%s[%d] = {' % (sym, len(entries)))
    for e in entries:
        f = func_of(e)
        delta = e - f
        if delta == 0 and f in declared:
            expr = '(char *)FUN_%08x' % f
        elif delta == 0:
            dec = decorated_for(f)
            if dec:
                ident = 'pt_a_%08x' % f
                if ident not in aliases:
                    aliases[ident] = dec
                    lines.insert(0, 'extern "C" void %s();' % ident)
                expr = '(char *)%s' % ident
            else:
                lines.append('    (void *)0x%08X,  // unmapped' % e)
                continue
        else:
            expr = '(char *)FUN_%08x + %d' % (f, delta)
        lines.append('    (void *)(%s),' % expr)
    lines.append('};')
    lines.append('')

open(OUT_CPP, 'w').write('\n'.join(lines) + '\n')
open(OUT_MAP, 'w').write('\n'.join(map_lines) + '\n')
with open('src/pt_vtable_alias.txt', 'w') as f:
    f.write('# generated by tools/gen_vtables.py: pt_a_<orig> -> decorated\n')
    for ident in sorted(aliases):
        f.write('%s %s\n' % (ident, aliases[ident]))
print('wrote %s (%d arrays) and %s' % (OUT_CPP, len(arrays), OUT_MAP))
