#!/usr/bin/env python3
"""Generate a linker "import sentinel" that pins the PE import table order.

MSVC link.exe assigns IAT slots in a way that depends on the object/relocation
order (the per-DLL slot list comes out as the *load order rotated left by one*,
where load order is, per object, the reverse of its import references).  That
depends on the original TU boundaries, which we do not reproduce, so our IAT
order differs from the original.

A single object placed FIRST in the link that references every import exactly
once makes the load order deterministic: the linker resolves its references
first, in reverse source order, and the remaining objects add nothing new.
This tool emits that object (`src/zzzzz_import_order.cpp`) with the reference
order chosen so the resulting IAT order matches the original exactly:

    desired IAT per DLL   O_dll
    load per DLL          = rotate-right(O_dll)
    sentinel source order = reverse(concat(load_per_dll))

Run before `make`.  The file is kept in the link by /INCLUDE.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

# descriptor order from the original
DESC_ORDER = ['WINMM.dll', 'VERSION.dll', 'WS2_32.dll', 'KERNEL32.dll',
              'USER32.dll', 'GDI32.dll', 'ADVAPI32.dll', 'ole32.dll',
              'OLEAUT32.dll', 'DSOUND.dll', 'DDRAW.dll']

# ordinal imports: original slot -> alias ident in pt_aliases.h
ORDINAL = {
    0x4bc24c: 'pt_imp_004bc24c',  # OLEAUT32 #9  VariantClear
    0x4bc250: 'pt_imp_004bc250',  # OLEAUT32 #8  VariantInit
    0x4bc384: 'pt_imp_004bc384',  # WS2_32 #19   send
    0x4bc01c: 'pt_imp_004bc01c',  # DSOUND #11   DirectSoundCreate8
}

# collect original IAT per DLL, in slot order
per_dll = {d: [] for d in DESC_ORDER}
for line in open('ghidra/export/imports.tsv'):
    a, dll, fn = line.rstrip('\n').split('\t')
    a = int(a, 16)
    if dll not in per_dll:
        per_dll[dll] = []
    per_dll[dll].append((a, fn))

load = []
for dll in DESC_ORDER:
    items = per_dll.get(dll, [])
    if not items:
        continue
    # rotate right by one
    rot = [items[-1]] + items[:-1]
    load.extend(rot)

src_order = list(reversed(load))

# headers that declare the imports we reference by name
INCLUDES = ['<windows.h>', '<mmsystem.h>', '<ddraw.h>',
            '<dsound.h>', '<objbase.h>', '<oleauto.h>']

lines = ['// auto-generated by tools/gen_import_sentinel.py — do not edit',
         '// Pins the import table order; see the tool docstring.',
         '']
for h in INCLUDES:
    lines.append('#include %s' % h)
lines += ['#include "pt_aliases.h"', '',
          '// Imports the SDK headers do not declare (referenced via inline asm).',
          'extern "C" __declspec(dllimport) void __stdcall RtlUnwind(void *, void *, void *, void *);',
          '',
          '#pragma comment(linker, "/INCLUDE:_pt_import_sentinel")', '',
          '// Place the (never-called) sentinel code at the very end of .text so it',
          '// does not disturb the game-region layout, while the object is still',
          '// FIRST in link order so its import references are resolved first.',
          '#pragma code_seg(".text$zz")',
          'extern "C" __declspec(naked) void pt_import_sentinel(void)',
          '{', '    __asm {']
for addr, fn in src_order:
    if addr in ORDINAL:
        lines.append('        mov eax, dword ptr [%s]' % ORDINAL[addr])
    elif re.match(r'^[A-Za-z_][A-Za-z0-9_]*$', fn):
        lines.append('        mov eax, dword ptr [%s]' % fn)
    else:
        raise SystemExit('unhandled import %s %s' % (hex(addr), fn))
lines += ['        ret', '    }', '}', '#pragma code_seg()', '']
open('src/00000_import_order.cpp', 'w').write('\n'.join(lines))
print('wrote src/00000_import_order.cpp with %d references' % len(src_order))
