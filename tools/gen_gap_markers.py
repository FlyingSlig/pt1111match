#!/usr/bin/env python3
"""Emit reccmp SYNTHETIC namerefs for code-gap starts referenced by switch
tables / pointer tables.

`tools/rewrite_layout_chunks.py` rewrites an absolute memory displacement that
falls inside a game-region gap to `gap_<gapstart> + delta`.  The original side
needs an entity at the gap start for the operand to normalise to the same
`gap_x+delta`; a SYNTHETIC nameref provides exactly that mapping (by mangled
symbol name, no body comparison).

Writes `src/0106_gap_markers.cpp` (comments only; the declarations come from
pt_aliases.h).  Run after gen_layout_chunks/add_missing_funcs, before the
rewriter.
"""
import csv
import glob
import os
import re
import re

from capstone import CS_ARCH_X86, CS_MODE_32, CS_OP_MEM, CS_OP_IMM, Cs

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

from ptconfig import ORIG_EXE
EXE = ORIG_EXE
d = open(EXE, 'rb').read()

sizes = {}
for row in csv.DictReader(open('ghidra/export/functions.tsv'), delimiter='\t'):
    sizes[int(row['addr'], 16)] = int(row['size'])

gaps = []
for r in csv.DictReader(open('ghidra/export/text_layout.tsv'), delimiter='\t'):
    if r['kind'] == 'gap' and int(r['start'], 16) < 0x496fa4:
        gaps.append((int(r['start'], 16), int(r['size'])))
gaps.sort()


def gap_for(a):
    lo, hi = 0, len(gaps)
    while lo < hi:
        mid = (lo + hi) // 2
        s, n = gaps[mid]
        if a < s:
            hi = mid
        elif a >= s + n:
            lo = mid + 1
        else:
            return s
    return None


md = Cs(CS_ARCH_X86, CS_MODE_32)
md.detail = True

used = set()
for addr, size in sizes.items():
    if addr >= 0x496fa4:
        continue
    off = 4096 + (addr - 0x400000 - 0x1000)
    fb = d[off:off + size]
    pos = 0
    while pos < len(fb):
        insn = next(md.disasm(fb[pos:pos + 15], addr + pos), None)
        if insn is None or insn.size == 0:
            pos += 1
            continue
        for op in insn.operands:
            if op.type == CS_OP_MEM and op.mem.disp != 0:
                g = gap_for(op.mem.disp & 0xffffffff)
                if g is not None:
                    used.add(g)

        pos += insn.size

# only reference gaps whose filler function is actually in our source
src = ''.join(open(f, errors='replace').read() for f in glob.glob('src/*_layout.cpp'))
used = sorted(g for g in used if ('gap_%08x' % g) in src)

out = ['// auto-generated by tools/gen_gap_markers.py',
       '// SYNTHETIC namerefs for code gaps referenced by absolute tables.',
       '// Nameref is the mangled gap filler symbol; no body is compared.',
       '']
for g in used:
    out.append('// SYNTHETIC: PORT1111 0x%08x' % g)
    out.append('// ?gap_%08x@@YAXXZ' % g)
    out.append('')
open('src/0106_gap_markers.cpp', 'w').write('\n'.join(out))

# The SYNTHETIC marker is function-category, so reccmp would compare the gap
# filler bytes as if they were decompiled functions and inflate the report.
# Keep the name mapping but exclude the gap entities from the report.
names = ['gap_%08x' % g for g in used]
if names:
    lst = '      ignore_functions:\n' + ''.join(
        '        - %s\n' % n for n in names)
else:
    lst = '      ignore_functions: []\n'
yml = open('reccmp-project.yml').read()
yml = re.sub(r'    report:\n      ignore_functions:[^\n]*\n(?:        - [^\n]*\n)*',
             '    report:\n' + lst, yml)
open('reccmp-project.yml', 'w').write(yml)
print('wrote %d gap markers (+ report ignore list)' % len(used))
