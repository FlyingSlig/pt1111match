#!/usr/bin/env python3
"""Rewrite our per-type STL callee references to the original's folded symbols.

The original binary was linked with ICF-like folding: identical template
instantiations of `_Tree` helpers (e.g. `_Lrotate`, `_Min`, `_Inc`,
`erase(iterator)` for the size-8 families) exist only once, shared by callers
of several different container types.  Our build (ICF off) compiles one copy
per fabricated type, so a caller's callee name never matches the TEMPLATE
nameref of the shared original address.

For every direct call edge A -> B between two TEMPLATE-marked original
functions whose fabricated type tags differ, this tool maps our caller's callee
symbol (same operation as B, tag of A) to the marker symbol at B and writes
`src/pt_callee_map.txt`.  `tools/patch_obj_syms.py` renames those undefined
symbols in the objects before link, so the call resolves to the marker's
symbol without changing any source or creating duplicate namerefs.

Run before `make` (the map is a link dependency). Idempotent.
"""
import collections
import csv
import glob
import os
import re

from capstone import CS_ARCH_X86, CS_MODE_32, CS_OP_IMM, Cs

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

from ptconfig import ORIG_EXE
EXE = ORIG_EXE


def tag(sym):
    for pat in ('_Tmap_traits@', '_Tset_traits@'):
        i = sym.find(pat)
        if i >= 0:
            j = sym.find('U?$less@', i)
            if j > 0:
                return sym[i + len(pat):j]
    return None


def op(sym):
    if sym.startswith('?_Erase@'):
        return '_Erase'
    if sym.startswith('?erase@'):
        return 'range' if sym.endswith('V312@0@Z') else 'iter'
    if sym.startswith('??1?$_Tree@'):
        return 'dtor'
    for n in ('_Inc', '_Min', '_Max', '_Lrotate', '_Rrotate', '_Insert',
              'find', 'lower_bound', 'count'):
        if sym.startswith('?' + n + '@'):
            return n
    return None


mark = {}
for fn in glob.glob('src/*.cpp'):
    lines = open(fn, errors='replace').read().splitlines()
    for i, l in enumerate(lines):
        m = re.match(r'\s*//\s*TEMPLATE:\s*PORT1111\s+(0x[0-9a-f]+)', l)
        if m:
            nx = lines[i + 1].strip() if i + 1 < len(lines) else ''
            mark[int(m.group(1), 16)] = nx[2:].strip() if nx.startswith('//') else nx

defined = set()
for l in open('build/Port1111.map', errors='replace'):
    m = re.match(r'\s*[0-9A-Fa-f]{4}:[0-9A-Fa-f]{8}\s+(\S+)\s+'
                 r'[0-9a-fA-F]{8}\s', l)
    if m:
        defined.add(m.group(1))

idx = {}
for s in defined:
    if '$_Tree@' not in s:
        continue
    t, o = tag(s), op(s)
    if t and o:
        idx[(o, t)] = s

sizes = {}
for row in csv.DictReader(open('ghidra/export/functions.tsv'), delimiter='\t'):
    sizes[int(row['addr'], 16)] = int(row['size'])

d = open(EXE, 'rb').read()
md = Cs(CS_ARCH_X86, CS_MODE_32)
md.detail = True


def get(va, n):
    off = 4096 + (va - 0x400000 - 0x1000)
    return d[off:off + n]


ren = {}
conflict = collections.defaultdict(set)
missing = 0
for a, sym in mark.items():
    if a not in sizes:
        continue
    ta, oa = tag(sym), op(sym)
    if not ta or not oa:
        continue
    off = 4096 + (a - 0x400000 - 0x1000)
    for ins in md.disasm(d[off:off + sizes[a]], a):
        if ins.mnemonic not in ('call', 'jmp') or not ins.operands:
            continue
        if ins.operands[0].type != CS_OP_IMM:
            continue
        b = ins.operands[0].imm & 0xffffffff
        if b not in mark or b == a:
            continue
        sb = mark[b]
        tb, ob = tag(sb), op(sb)
        if not tb or not ob or tb == ta:
            continue
        ca = idx.get((ob, ta))
        if not ca:
            missing += 1
            continue
        conflict[ca].add(sb)
        ren[ca] = sb

bad = [k for k, v in conflict.items() if len(v) > 1]
if bad:
    print('CONFLICT: %d symbols map to multiple targets, skipping them' % len(bad))
    for k in bad:
        print(' ', k[:80])
        ren.pop(k, None)

with open('src/pt_callee_map.txt', 'w') as f:
    f.write('# auto-generated by tools/gen_stl_callee_renames.py\n')
    f.write('# old (our per-type callee) -> new (original folded marker symbol)\n')
    for old in sorted(ren):
        f.write('%s %s\n' % (old, ren[old]))
print('wrote %d callee renames (missing instantiations: %d)' % (len(ren), missing))
